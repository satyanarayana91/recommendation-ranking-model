"""Run core SQLite data-validation checks against MovieLens 100K locally."""

from __future__ import annotations

import sqlite3
from pathlib import Path

import pandas as pd


RAW_PATH = Path("data/raw/ml-100k/u.data")
REPORT_PATH = Path("reports/sql_validation.md")


def scalar(connection: sqlite3.Connection, query: str) -> int:
    return int(connection.execute(query).fetchone()[0])


def main() -> None:
    if not RAW_PATH.exists():
        raise FileNotFoundError("Run `python src/download_movielens_100k.py` first.")
    ratings = pd.read_csv(
        RAW_PATH, sep="\t", names=["user_id", "movie_id", "rating", "timestamp"], header=None
    )
    with sqlite3.connect(":memory:") as connection:
        ratings.to_sql("ratings", connection, index=False, if_exists="replace")
        rows = scalar(connection, "SELECT COUNT(*) FROM ratings")
        invalid = scalar(connection, "SELECT COUNT(*) FROM ratings WHERE rating NOT BETWEEN 1 AND 5")
        nulls = connection.execute(
            "SELECT SUM(user_id IS NULL), SUM(movie_id IS NULL), SUM(rating IS NULL), "
            "SUM(timestamp IS NULL) FROM ratings"
        ).fetchone()
        exact_duplicates = scalar(
            connection,
            "SELECT COUNT(*) FROM (SELECT 1 FROM ratings GROUP BY user_id, movie_id, rating, timestamp HAVING COUNT(*) > 1)",
        )
        repeated_pairs = scalar(
            connection,
            "SELECT COUNT(*) FROM (SELECT 1 FROM ratings GROUP BY user_id, movie_id HAVING COUNT(*) > 1)",
        )
        top_items = connection.execute(
            "SELECT movie_id, COUNT(*) AS interactions FROM ratings GROUP BY movie_id "
            "ORDER BY interactions DESC, movie_id LIMIT 5"
        ).fetchall()

    REPORT_PATH.write_text(
        "# SQL Validation Practice\n\n"
        "Generated by `python src/run_sql_validation.py` using an in-memory SQLite table loaded from the local raw ratings file. "
        "The reusable query examples are in `sql/recommendation_validation.sql`.\n\n"
        "## Verified checks\n\n"
        f"- Loaded rows: **{rows:,}**\n"
        f"- Invalid ratings outside 1–5: **{invalid:,}**\n"
        f"- NULL counts (`user_id`, `movie_id`, `rating`, `timestamp`): **{', '.join(str(int(value)) for value in nulls)}**\n"
        f"- Exact duplicate groups: **{exact_duplicates:,}**\n"
        f"- Repeated user–movie pair groups: **{repeated_pairs:,}**\n\n"
        "## Top movies by all-period interaction count\n\n"
        "| movie_id | interactions |\n| ---: | ---: |\n"
        + "".join(f"| {movie_id} | {count:,} |\n" for movie_id, count in top_items)
        + "\nThis all-period aggregation validates SQL syntax and data shape only. It must not be used as an evaluation baseline because it includes future interactions. The implemented baseline accepts training-period data explicitly.\n",
        encoding="utf-8",
    )
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
