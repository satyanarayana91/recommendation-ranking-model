"""Create a deterministic, reviewable demonstration of the ranking endpoint."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
from xgboost import XGBRanker

import app as ranking_api
from src.run_ranking_experiment import FEATURE_COLUMNS, RAW_PATH, candidates, feature_matrix, split_per_user


REQUEST_PATH = Path("reports/demo_request.json")
RESPONSE_PATH = Path("reports/demo_response.json")
REPORT_PATH = Path("reports/demo_run.md")
DEMO_USER_ID = 842


def main() -> None:
    if not RAW_PATH.exists() or not ranking_api.MODEL_PATH.exists():
        raise FileNotFoundError("Run `python -m src.run_ranking_experiment` first.")
    ratings = pd.read_csv(RAW_PATH, sep="\t", names=["user_id", "movie_id", "rating", "timestamp"], header=None)
    train, validation, test = split_per_user(ratings)
    history = pd.concat([train, validation], ignore_index=True)
    candidate_rows = feature_matrix(candidates(test, history, ratings.movie_id.unique()), history)
    user_rows = candidate_rows.loc[candidate_rows.user_id == DEMO_USER_ID].head(5).copy()
    if len(user_rows) < 2:
        raise ValueError(f"Demo user {DEMO_USER_ID} does not have enough candidates")
    payload = {
        "user_id": str(DEMO_USER_ID),
        "top_k": 3,
        "candidates": [
            {"item_id": str(row.movie_id), "features": {feature: float(getattr(row, feature)) for feature in FEATURE_COLUMNS}}
            for row in user_rows.itertuples(index=False)
        ],
    }
    model = XGBRanker()
    model.load_model(str(ranking_api.MODEL_PATH))
    ranking_api.app.state.rank_model = model
    response = ranking_api.rank_items(ranking_api.RankRequest.model_validate(payload)).model_dump()
    REQUEST_PATH.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    RESPONSE_PATH.write_text(json.dumps(response, indent=2), encoding="utf-8")
    REPORT_PATH.write_text(
        "# Recommendation Ranking Demo\n\n"
        "Generated by `python -m src.run_demo` using the actual saved XGBoost artifact and the same `/rank` request handler used by FastAPI. The request contains five deterministic held-out candidates for MovieLens user 842, with precomputed historical features; it does not demonstrate candidate generation inside the API.\n\n"
        f"- Request: `reports/demo_request.json`\n- Response: `reports/demo_response.json`\n- Candidates submitted: **{len(payload['candidates'])}**; results returned (`top_k=3`): **{response['returned_count']}**.\n\n"
        "The returned scores are ranking scores, not probabilities. The endpoint checks feature names and values, scores candidates, sorts descending, and applies `top_k`. To demonstrate the HTTP server interactively, run `uvicorn app:app --reload` and use `/docs` with the saved request.\n",
        encoding="utf-8",
    )
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
