"""Produce a reproducible EDA report for the MovieLens 100K ratings table."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


RAW_PATH = Path("data/raw/ml-100k/u.data")
REPORT_PATH = Path("reports/dataset_eda.md")
COLUMNS = ["user_id", "movie_id", "rating", "timestamp"]
RELEVANCE_THRESHOLD = 4


def fmt_number(value: int | float) -> str:
    return f"{value:,}" if isinstance(value, int) else f"{value:,.4f}"


def describe_series(series: pd.Series) -> dict[str, float]:
    description = series.describe()
    return {key: float(description[key]) for key in ("min", "25%", "50%", "mean", "75%", "max")}


def main() -> None:
    if not RAW_PATH.exists():
        raise FileNotFoundError(
            f"{RAW_PATH} is missing. Run `python src/download_movielens_100k.py` first."
        )

    df = pd.read_csv(RAW_PATH, sep="\t", names=COLUMNS, header=None)
    df["timestamp"] = pd.to_datetime(df["timestamp"], unit="s", utc=True)
    df["relevance"] = (df["rating"] >= RELEVANCE_THRESHOLD).astype("int8")

    missing = df.isna().sum()
    exact_duplicates = int(df.duplicated().sum())
    pair_counts = df.groupby(["user_id", "movie_id"]).size()
    repeated_pairs = int((pair_counts > 1).sum())
    users = int(df["user_id"].nunique())
    items = int(df["movie_id"].nunique())
    unique_pairs = int(pair_counts.size)
    density = unique_pairs / (users * items)
    user_activity = df.groupby("user_id").size()
    item_activity = df.groupby("movie_id").size()
    ratings = df["rating"].value_counts().sort_index()
    labels = df["relevance"].value_counts().sort_index()
    invalid_ratings = int((~df["rating"].between(1, 5)).sum())
    timestamp_min, timestamp_max = df["timestamp"].min(), df["timestamp"].max()

    user_stats = describe_series(user_activity)
    item_stats = describe_series(item_activity)
    report = f"""# Dataset Selection and EDA

Generated by `python src/run_eda.py` from the local raw rating file. Values below are observed output, not estimates.

## 1. Objective

This project will rank candidate movies for a user. The EDA verifies that the selected data contains a user grouping key, an item key, a relevance signal, and timestamps that can support a leakage-aware evaluation design. Model training and ranking metrics are out of scope for this report.

## 2. Dataset Source

- **Dataset:** MovieLens 100K, GroupLens Research at the University of Minnesota.
- **Official dataset page:** <https://grouplens.org/datasets/movielens/100k/>.
- **Retrieved files:** `u.data` and the accompanying `README` from <https://files.grouplens.org/datasets/movielens/ml-100k/>.
- **Version:** stable MovieLens 100K release (released April 1998; the source README describes ratings collected from 19 September 1997 through 22 April 1998).
- **Terms:** the accompanying README permits research use subject to acknowledgement and no implied endorsement; redistribution and commercial/revenue-bearing use require separate permission. Raw data is therefore ignored by this repository. Review the downloaded README before use or publication.
- **Retrieval:** run `python src/download_movielens_100k.py`, then `python src/run_eda.py`.

## 3. Dataset Schema

| Column | Observed dtype | Meaning | Role |
| --- | --- | --- | --- |
| `user_id` | `{df['user_id'].dtype}` | Consecutively numbered MovieLens user identifier | Ranking group key; identifier, not a continuous feature |
| `movie_id` | `{df['movie_id'].dtype}` | Consecutively numbered movie identifier | Candidate-item key; identifier, not a continuous feature |
| `rating` | `{df['rating'].dtype}` | Recorded 1–5 user rating | Graded relevance signal / source for binary label |
| `timestamp` | `{df['timestamp'].dtype}` | UTC time converted from Unix seconds | Temporal analysis and split design |
| `relevance` | `{df['relevance'].dtype}` | `1` when rating is at least {RELEVANCE_THRESHOLD}; otherwise `0` | Experimental binary relevance label |

## 4. Dataset Size

- Rows: **{fmt_number(len(df))}**
- Columns in raw ratings file: **4** (the derived `relevance` column is not raw data)
- Distinct users: **{fmt_number(users)}**
- Distinct movies: **{fmt_number(items)}**
- Unique user–movie pairs: **{fmt_number(unique_pairs)}**
- Observed timestamps: **{timestamp_min.date()}** through **{timestamp_max.date()}** (UTC)

## 5. Data Quality

- Missing values: `{', '.join(f'{column}={int(count)}' for column, count in missing.items())}`.
- Exact duplicate rows: **{fmt_number(exact_duplicates)}**.
- Repeated user–movie pairs: **{fmt_number(repeated_pairs)}**. In this file each observed pair is unique, so pair count equals row count.
- Invalid ratings outside the documented 1–5 range: **{fmt_number(invalid_ratings)}**.

The EDA validates the ratings table only. Item metadata and user demographics are separate source files and are not used as features in this first ranking dataset definition.

## 6. Distribution Analysis

### Ratings and relevance

| Rating | Interactions |
| ---: | ---: |
{''.join(f'| {int(rating)} | {fmt_number(int(count))} |\n' for rating, count in ratings.items())}

With the documented experimental definition `relevance = (rating >= {RELEVANCE_THRESHOLD})`, **{fmt_number(int(labels.get(1, 0)))} ({labels.get(1, 0) / len(df):.2%})** interactions are relevant and **{fmt_number(int(labels.get(0, 0)))} ({labels.get(0, 0) / len(df):.2%})** are not.

### Interaction sparsity and activity

- Interaction density: **{density:.4%}** = {fmt_number(unique_pairs)} unique observed pairs / ({fmt_number(users)} users × {fmt_number(items)} movies).
- User interactions: min **{fmt_number(int(user_stats['min']))}**, median **{user_stats['50%']:.1f}**, mean **{user_stats['mean']:.2f}**, 75th percentile **{user_stats['75%']:.1f}**, max **{fmt_number(int(user_stats['max']))}**.
- Movie interactions: min **{fmt_number(int(item_stats['min']))}**, median **{item_stats['50%']:.1f}**, mean **{item_stats['mean']:.2f}**, 75th percentile **{item_stats['75%']:.1f}**, max **{fmt_number(int(item_stats['max']))}**.

The low density confirms a sparse user–item matrix. The activity ranges show an interaction long tail: some movies have minimal history while some users and movies have substantially more observations. This creates cold-start and popularity-bias risks for later experiments.

## 7. Relevance Definition

The raw `rating` remains the primary **graded** relevance signal because a 1–5 rating preserves preference intensity. For binary ranking experiments, this report defines `relevance = 1` for ratings of 4 or 5 and `0` otherwise. The threshold is a transparent experimental convention for a 1–5 rating scale, not a claim that a low rating is an explicit negative interaction. It must remain fixed across baseline and model comparisons.

## 8. Ranking Readiness

`user_id` provides a natural ranking group, `movie_id` identifies candidates, and each interaction provides a rating-derived relevance signal. The source states that every included user has at least 20 ratings, so each observed user group has multiple judged items. However, ratings alone are observed interactions, not an exposure log: unobserved movies must not automatically be treated as irrelevant without a separately documented negative-sampling policy. Low-history movies remain cold-start candidates.

## 9. Leakage Risks

- Do not use the target rating or its binary transformation as a feature.
- User activity, user preference summaries, and item popularity must be computed only from the training period for each split.
- Do not use future timestamps, future ratings, or aggregates that include validation/test rows.
- The supplied rating file is randomly ordered; sort by timestamp before a temporal split.
- If generating negative candidates from unobserved movies, do so within the permitted time boundary and document the sampling rule.

## 10. Planned Evaluation

Use a chronological per-user holdout: sort each user's interactions by timestamp, reserve the most recent eligible interactions for validation/test, and retain earlier interactions for training. Construct candidate sets using only information available before each holdout timestamp. Exclude user groups that cannot satisfy the minimum-history rule, and report the exclusion count. Evaluate a popularity baseline and later model on identical candidates with NDCG@K (graded ratings where appropriate) and MRR (using the fixed binary definition), without reporting metrics until the implementation is complete.

## 11. Limitations

- MovieLens 100K is a historical, small benchmark; its 1997–1998 ratings may not represent current viewing behavior.
- It is designed for recommendation research, not search-query/document relevance.
- The dataset contains explicit ratings but no impression/exposure data, so missing interactions are ambiguous.
- User selection and the minimum 20-rating inclusion rule introduce selection bias.
- Sparse and long-tail interactions make cold-start behavior difficult to assess from ratings alone.
- Dataset terms restrict redistribution and commercial/revenue-bearing use without permission.

## 12. Next Steps

1. Decide and document candidate/negative sampling for the temporal holdout.
2. Implement leakage-safe training-period user and item aggregates.
3. Build a popularity baseline and validate NDCG@K and MRR calculations on hand-checked examples.
4. Train and evaluate a ranking model only after candidate sets and split logic are verified.
"""
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"Wrote {REPORT_PATH}")
    print(f"Rows={len(df)}, users={users}, movies={items}, density={density:.4%}")


if __name__ == "__main__":
    main()
